#!/usr/bin/env node
// Writes src/styles/fonts.css from the vendored OFL font (vendor/fonts/*.woff2) as a base64 @font-face rule. A page opened
// from file:// cannot load a font from a url(), so the face travels inside the stylesheet that the build inlines.
//   node tools/build-fonts.mjs
// Titan One has one weight (400). The rule declares 100 to 900, so the headings' 900 matches it instead of a smeared fake bold.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FACES = [['Titan One', 'titan-one-latin-400-normal.woff2']];
let css = '/* Generated by tools/build-fonts.mjs from vendor/fonts (SIL Open Font License 1.1, see vendor/fonts/OFL-titan-one.txt). Do not edit. */\n';
for (const [family, file] of FACES) {
  const b64 = fs.readFileSync(path.join(GAME, 'vendor', 'fonts', file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:normal;font-weight:100 900;font-display:block;src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.writeFileSync(path.join(GAME, 'src', 'styles', 'fonts.css'), css);
console.log('src/styles/fonts.css', (css.length / 1024).toFixed(1), 'KB');
