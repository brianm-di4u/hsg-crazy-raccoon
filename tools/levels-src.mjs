// Campaign level sources. tools/build-levels.mjs solves each one, sets its par time and writes data/levels.json.
// Rows run bottom (row 0, the start) to top (the den). Positions `at` are in tiles along the 15-tile lane span,
// columns `c` are 0..8. Layouts are imagined for the game (research/town-content.md §5).

