const C = (at, n = 3, o = {}) => ({ k: 'conga', at, n, len: 3, ...o });
const WH = (at, fling = 2, o = {}) => ({ k: 'whipper', at, fling, len: 3, ...o });
const H = (at) => ({ k: 'hatchling', at, len: 1 });
const B = (at, len = 3, o = {}) => ({ k: 'basker', at, len, ...o });
const S = (col, len = 2, o = {}) => ({ k: 'sleeper', at: col + 3, len, ...o });
const water = (dir, v, g, o = {}) => ({ t: 'water', dir, v, g, ...o });
const land = (t, dir, v, g, o = {}) => ({ t, dir, v, g, ...o });
const safe = (t = 'grass', o = {}) => ({ t, ...o });
const check = (t = 'grass', o = {}) => ({ t, check: true, ...o });
const fence = (gaps, o = {}) => ({ t: 'fence', gaps, ...o });
const I = (r, c, k) => ({ r, c, k });

