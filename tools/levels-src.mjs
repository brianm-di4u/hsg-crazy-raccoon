  const tu = TUNE[L.id] || {};
  // tail rings: 5 in zones 1-3, 4 in the barn, 3 on the midnight raid (Assist adds 2)
  L.rings = L.rings || (L.zone >= 5 ? 3 : L.zone === 4 ? 4 : 5);
  let lane = 0;
  L.rows.forEach((r) => {
    if (!r.g) return;
    if (tu.vm && r.v) r.v = +(r.v * tu.vm).toFixed(2);
    if (tu.sjaw) r.g.forEach((g) => { if (g.k === 'sleeper') g.jaw = tu.sjaw; });
    if (r.t !== 'water') return;
    lane++;
    if (tu.jaw) r.g.forEach((g) => { if (g.k === 'paddler' || g.k === 'whipper' || g.k === 'conga') g.jaw = tu.jaw; });
    if (tu.thin && lane % tu.thin === 0 && r.g.length >= 3 && !r.g.some((g) => g.k === 'boss')) r.g.pop();
  });
